/**
 * Récupère la méditation du jour basée sur la date calendaire (1-31)
 */
export const getTodayMeditation = () => {
  const dayOfMonth = new Date().getDate(); // 1 à 31
  const index = (dayOfMonth - 1) % DAILY_MEDITATIONS.length;
  return DAILY_MEDITATIONS[index];
};
